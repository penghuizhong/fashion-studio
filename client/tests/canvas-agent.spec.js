import { test,expect } from '@playwright/test';
import sharp from '../../server/node_modules/sharp/lib/index.js';
for(const width of [1440,390])test(`Pi Agent confirms budget, uses skills, generates and lays out without duplicates ${width}`,async({page,request})=>{
  await page.setViewportSize({width,height:1050});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const {project}=await(await request.post('/api/canvas/projects',{data:{title:'Pi Agent browser'}})).json();
  await page.addInitScript(id=>localStorage.setItem('fashion-canvas-last:local',id),project.id);
  await page.goto('/');
  if(width<769)await page.getByRole('button',{name:'打开侧边栏',exact:true}).click();
  await page.getByRole('button',{name:'万能画板',exact:true}).click();
  await expect(page.locator('.tl-canvas')).toBeVisible();
  const buffer=await sharp({create:{width:150,height:220,channels:3,background:'#c3bbbb'}}).png().toBuffer();
  await page.getByLabel('上传画板图片',{exact:true}).setInputFiles([{name:'服装.png',mimeType:'image/png',buffer},{name:'模特.png',mimeType:'image/png',buffer:await sharp(buffer).tint('#aabbcc').png().toBuffer()}]);
  await expect(page.locator('.canvas-layer')).toHaveCount(2);
  await page.locator('.canvas-layer-name').filter({hasText:'服装.png'}).click();
  await page.locator('.canvas-layer-name').filter({hasText:'模特.png'}).click({modifiers:['Shift']});
  await expect(page.locator('.canvas-ref-chip')).toHaveCount(2);
  await page.getByRole('button',{name:'单步生成 · 切换多步 Agent',exact:true}).click();
  await page.getByLabel('Agent 图1角色',{exact:true}).selectOption('garment');
  await page.getByLabel('Agent 图2角色',{exact:true}).selectOption('model');
  await page.getByLabel('Agent 图片上限',{exact:true}).selectOption('3');
  await page.locator('.canvas-composer textarea').fill('按服装和模特做三个视角，再排版');
  await page.getByRole('button',{name:'查看 Agent 费用上限',exact:true}).click();
  await expect(page.getByLabel('多步 Agent 费用确认')).toBeVisible();
  expect((await(await request.get(`/api/canvas/projects/${project.id}/agent-runs`)).json()).runs).toHaveLength(0);
  await page.getByRole('button',{name:'确认规划费用并分析',exact:true}).click();
  await expect(page.getByLabel('多步 Agent 任务').getByText('多步 Agent · 等待确认执行费用',{exact:true})).toBeVisible({timeout:15000});
  expect((await(await request.get(`/api/canvas/projects/${project.id}/runs`)).json()).runs).toHaveLength(0);
  await page.getByRole('button',{name:'查看继续执行费用',exact:true}).click();
  await page.getByRole('button',{name:'确认费用并继续原任务',exact:true}).click();
  await expect(page.getByLabel('多步 Agent 任务').getByText('多步 Agent · 已完成',{exact:true})).toBeVisible({timeout:20000});
  await expect(page.locator('.canvas-layer')).toHaveCount(5,{timeout:15000});
  await expect.poll(async()=>{const r=await(await request.get(`/api/canvas/projects/${project.id}/agent-runs`)).json();return r.runs[0]?.result.layout?.delivered;}).toBe(true);
  const saved=await(await request.get(`/api/canvas/projects/${project.id}`)).json();
  const shapes=Object.values(saved.project.snapshot.document.store).filter(s=>s.typeName==='shape'&&s.meta?.agentLayoutId);
  expect(shapes).toHaveLength(3);expect(new Set(shapes.map(s=>s.y)).size).toBe(1);expect(new Set(shapes.map(s=>s.x)).size).toBe(3);
  await page.reload();
  if(width<769)await page.getByRole('button',{name:'打开侧边栏',exact:true}).click();
  await page.getByRole('button',{name:'万能画板',exact:true}).click();
  await expect(page.locator('.canvas-layer')).toHaveCount(5);
  expect((await(await request.get(`/api/canvas/projects/${project.id}/runs`)).json()).runs).toHaveLength(3);
  expect(errors).toEqual([]);
});
